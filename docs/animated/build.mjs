// Wraps each approved README diagram (docs/diagrams/<name>-<theme>.html) in a HyperFrames
// composition at 1440×900: the <svg> is copied verbatim and diagram.js adds the motion.
// usage (from docs/animated): node build.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

mkdirSync("compositions", { recursive: true });
for (const name of ["architecture", "admin-auth"]) {
  for (const theme of ["dark", "light"]) {
    const src = readFileSync(`../diagrams/${name}-${theme}.html`, "utf8");
    const svg = src.match(/<svg[\s\S]*?<\/svg>/)[0].replace("<svg ", '<svg id="dia" width="1440" height="900" ');
    const fonts = src.match(/<link href="(https:\/\/fonts[^"]+)"/)[1].replace("display=swap", "display=block");
    const bg = svg.match(/<rect width="100%" height="100%" fill="([^"]+)"/)[1];
    // Same timing constants as diagram.js: boxes, then one step per arrow, then a 3 s hold
    const boxes = (svg.match(new RegExp(`rx="6" fill="${bg}"`, "g")) || []).length;
    const arrows = (svg.match(/<path [^>]*marker-end/g) || []).length;
    const duration = Math.ceil(0.6 + boxes * 0.15 + 0.9 + arrows * 1.0 + 3);
    writeFileSync(`compositions/${name}-${theme}.html`, `<!doctype html>
<!-- Generated by docs/animated/build.mjs from docs/diagrams/${name}-${theme}.html — edit that file, not this one. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1440, height=900" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <link href="${fonts}" rel="stylesheet" />
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1440px; height: 900px; overflow: hidden; background: ${bg}; }
      #root, #dia { position: absolute; inset: 0; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${duration}" data-width="1440" data-height="900">
      ${svg}
      <script src="../diagram.js"></script>
      <script>
        window.__timelines["main"] = SpotifyDiagram.animate(document.getElementById("dia"), ${duration});
      </script>
    </div>
  </body>
</html>
`);
    console.log(`${name}-${theme}: ${boxes} boxes, ${arrows} arrows, ${duration}s`);
  }
}
